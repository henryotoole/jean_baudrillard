"""Emit ``infra/secrets/example.env``.

The example.env is a committed, keys-only manifest of the operator-
supplied secrets the project requires, grouped by service with comment
headers (cicl.md § example.env, config_and_secrets.md § 2.1):

- each core service's ``secrets:`` block (bespoke, operator-supplied
  secrets like API keys / tokens), and
- each backing engine's ``env:`` vars whose ``kind`` is ``secret``.

Engine env vars of kind ``fixed`` (inlined at compile) and ``minted``
(generated by docex into the TTE store) are deliberately excluded — they
are never operator-supplied, so they have no place in a secrets manifest.

The key set is derived from ``secret_manifest`` (cicl/categories.py) — the
single source of truth shared with ``docex secrets scaffold/status`` — so the
manifest and example.env can never drift.
"""

from __future__ import annotations

from itertools import groupby
from pathlib import Path
from typing import Mapping

from docex.cicl.categories import SecretEntry, secret_manifest
from docex.cicl.model import CICLDocument
from docex.cicl.transfer import TransferTables


def _group_header(source: str, doc: CICLDocument) -> str:
    """The grouped comment header for one manifest source. Matches the
    historical example.env layout: a doctrine block, then ``# <svc>
    (core service)`` blocks, then ``# <svc> (<engines>)`` backing blocks."""
    if source == "doctrine":
        return "# Doctrine-injected secrets"
    if source in doc.core_services:
        return f"# {source} (core service)"
    svc = doc.backing_services.get(source)
    if svc is not None:
        engines = svc.engine if isinstance(svc.engine, list) else [svc.engine]
        return f"# {source} ({', '.join(engines)})"
    return f"# {source}"


def render_manifest_env(
    doc: CICLDocument,
    tables: TransferTables,
    *,
    prefix_lines: list[str],
    values: Mapping[str, str],
) -> str:
    """Render the grouped-by-source env text for the secret manifest.

    ``prefix_lines`` are emitted verbatim (already ``#``-prefixed) at the top.
    Each key is written as ``KEY=<value>`` using ``values`` (empty string when
    absent) — example.env passes an empty mapping (keys only); ``secrets
    scaffold`` passes the reconciled values so the two share one layout."""
    lines = list(prefix_lines)
    manifest = secret_manifest(doc, tables)
    if not manifest:
        lines.append("# (no backing services declare runtime env vars)")
        return "\n".join(lines)
    for source, group in groupby(manifest, key=lambda e: e.source):
        lines.append(_group_header(source, doc))
        entry: SecretEntry
        for entry in group:
            if entry.desc:
                lines.append(f"# {entry.desc}")
            lines.append(f"{entry.key}={values.get(entry.key, '')}")
        lines.append("")
    return "\n".join(lines)


def emit_example_env(
    doc: CICLDocument, tables: TransferTables, out_path: Path
) -> None:
    prefix = [
        "# Generated by `docex compile`. Do not edit by hand.",
        "# Keys-only manifest of the operator-supplied secrets this project",
        "# requires. Reconcile it into <env>.env with",
        "# `docex secrets scaffold <env>`; never fill values in here.",
        "",
    ]
    out_path.write_text(
        render_manifest_env(doc, tables, prefix_lines=prefix, values={})
    )
